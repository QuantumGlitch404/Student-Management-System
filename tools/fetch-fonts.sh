#!/usr/bin/env bash
# Downloads the latin woff2 files for the SMS typography system and writes
# StudentManagementSystem/Content/css/fonts.css with local @font-face rules.
# Re-runnable: existing files are skipped.
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/StudentManagementSystem/Content/fonts"
CSS="$ROOT/StudentManagementSystem/Content/css/fonts.css"
mkdir -p "$OUT"

UA="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36"

# family:weights:slug:role
FAMILIES=(
  "Space+Grotesk:600;700:space-grotesk"
  "Sora:600;700:sora"
  "Manrope:400;500;600;700:manrope"
  "Outfit:500;600:outfit"
  "Plus+Jakarta+Sans:400;500;600;700:plus-jakarta-sans"
  "DM+Sans:400;500:dm-sans"
  "IBM+Plex+Mono:400;500:ibm-plex-mono"
  "Urbanist:700;800:urbanist"
  "Oxanium:500;600:oxanium"
  "Michroma:400:michroma"
)

: > "$CSS"
{
  echo "/* Student Management System - self-hosted typography (latin subset)."
  echo "   Generated by tools/fetch-fonts.sh - do not edit by hand. */"
  echo
} >> "$CSS"

for entry in "${FAMILIES[@]}"; do
  fam="${entry%%:*}"; rest="${entry#*:}"
  weights="${rest%%:*}"; slug="${rest#*:}"
  query="family=${fam}:wght@${weights}"
  css_json=$(curl -s -L -H "User-Agent: $UA" "https://fonts.googleapis.com/css2?${query}&display=swap")
  family_name=$(echo "$css_json" | grep -oE "font-family: '[^']+'" | head -1 | sed -E "s/font-family: '([^']+)'/\1/")
  [ -z "$family_name" ] && { echo "SKIP $slug (no css)"; continue; }

  # Walk @font-face blocks, keep only the latin unicode-range one.
  echo "$css_json" | awk -v RS='@font-face' 'NR>1 && /U\+0000-00FF/ {
      w=""; u="";
      if (match($0, /font-weight: [0-9]+/)) w = substr($0, RSTART+13, RLENGTH-13);
      if (match($0, /https:\/\/[^)]+\.woff2/)) u = substr($0, RSTART, RLENGTH);
      if (w != "" && u != "") print w "|" u;
    }' | while IFS='|' read -r weight url; do
    [ -z "${weight:-}" ] && continue
    [ -z "${url:-}" ] && continue
    file="${slug}-${weight}.woff2"
    if [ ! -s "$OUT/$file" ]; then
      curl -s -L -o "$OUT/$file" "$url" || { echo "FAIL $file"; continue; }
    fi
    printf "@font-face {\n  font-family: '%s';\n  font-style: normal;\n  font-weight: %s;\n  font-display: swap;\n  src: url('/Content/fonts/%s') format('woff2');\n}\n\n" \
      "$family_name" "$weight" "$file" >> "$CSS"
    echo "ok $file"
  done
done

echo "--- fonts on disk: $(ls -1 "$OUT" | wc -l) ---"
du -sh "$OUT" 2>/dev/null
echo "--- css rules: $(grep -c '@font-face' "$CSS") ---"
