using System;
using System.Collections.Generic;
using System.Data;
using System.Globalization;
using System.IO;
using System.Text;
using StudentManagementSystem.Lib;

namespace StudentManagementSystem.Reporting
{
    /// <summary>
    /// Structured, multi-page PDF report built on SimplePdf.
    ///
    /// Every page carries the application name, report title, generation time
    /// and a "Page n of N" footer. Tables repeat their header after a page
    /// break, wrap long cell text (nothing is cut off), shade alternate rows
    /// and switch to landscape automatically when many columns are present.
    /// </summary>
    public class PdfReport
    {
        private const float Margin = 38f;
        private readonly SimplePdf _pdf;
        private readonly float _width;
        private readonly float _height;
        private readonly string _title;
        private readonly string _subtitle;
        private readonly string _filters;
        private readonly string _generated;
        private readonly bool _landscape;
        private readonly string _zone;
        private float _y;
        private bool _started;

        public PdfReport(string title, string subtitle, string filters, bool landscape, string zone = null)
        {
            _landscape = landscape;
            _zone = string.IsNullOrWhiteSpace(zone) ? "UTC" : zone;
            _pdf = new SimplePdf(landscape);
            _width = _pdf.Width;
            _height = _pdf.Height;
            _title = Clean(title, 120);
            _subtitle = Clean(subtitle, 160);
            _filters = Clean(filters, 220);
            _generated = Fmt.Stamp(DateTime.UtcNow, _zone, "dd MMM yyyy, HH:mm") + " (" + _zone + ")";
        }

        /// <summary>Static facts shown under the title before the table (e.g. "Students: 12").</summary>
        public List<string> Summary { get; set; } = new List<string>();

        public byte[] Build()
        {
            EnsureStarted();
            Finish();
            _pdf.AppendFooters("Student Management System  \u00b7  " + _generated + "  \u00b7  generated by SMS 2.0",
                "Page {0} of {1}", Margin, 7);
            using (var ms = new MemoryStream())
            {
                _pdf.WriteTo(ms);
                return ms.ToArray();
            }
        }

        private void EnsureStarted()
        {
            if (_started) return;
            _started = true;
            StartPage(true);
            if (Summary.Count > 0) DrawSummary();
        }

        private void StartPage(bool first)
        {
            if (!first) _pdf.NewPage();
            _pdf.Rect(0, 0, _width, _height, true, 1f);
            _pdf.Rect(0, 0, _width, 66, true, 0.955f);
            _pdf.Gray(0.12f);
            _pdf.Text(Margin, 20, 7.5f, true, "STUDENT MANAGEMENT SYSTEM");
            _pdf.Text(Margin, 34, 16, true, _title);
            float rightX = _width - Margin - 170;
            _pdf.Gray(0.32f);
            _pdf.Text(rightX, 21, 7.5f, false, "Generated " + _generated);
            _pdf.Text(rightX, 32, 7.5f, false, "Report: " + (_landscape ? "A4 landscape" : "A4 portrait"));
            _pdf.Text(rightX, 43, 7.5f, false, "Records in this report are access-controlled.");
            _pdf.Gray(0);
            _pdf.LineWidth(0.7f);
            _pdf.Rule(Margin, 66, _width - Margin, 66);
            _y = 80;
            if (!string.IsNullOrEmpty(_subtitle))
            {
                _pdf.Gray(0.25f);
                _pdf.Text(Margin, _y, 8.5f, false, _subtitle);
                _y += 13;
            }
            if (!string.IsNullOrEmpty(_filters))
            {
                _pdf.Gray(0.38f);
                foreach (string part in Wrap(_filters, _width - Margin * 2, 7.5f, false))
                {
                    _pdf.Text(Margin, _y, 7.5f, false, part);
                    _y += 10;
                }
            }
            _pdf.Gray(0);
        }

        private void DrawSummary()
        {
            _pdf.Gray(0.2f);
            _pdf.Text(Margin, _y, 8, true, "SUMMARY");
            _y += 13;
            float colWidth = (_width - Margin * 2) / 2f;
            for (int i = 0; i < Summary.Count; i++)
            {
                float x = Margin + (i % 2) * colWidth;
                _pdf.Gray(0.15f);
                _pdf.Text(x, _y, 8, false, Clean(Summary[i], 110));
                if (i % 2 == 1) _y += 12;
            }
            if (Summary.Count % 2 == 1) _y += 12;
            _y += 4;
        }

        /// <summary>Adds a table with all of its columns. Long text wraps, never truncates.</summary>
        public void AddTable(DataTable table, string sectionHeading)
        {
            if (table == null) return;
            EnsureStarted();
            int count = table.Rows.Count;
            float fontSize = table.Columns.Count > 8 ? 6.8f : table.Columns.Count > 6 ? 7.2f : 7.8f;
            float lineHeight = fontSize + 2.5f;

            if (!string.IsNullOrEmpty(sectionHeading))
            {
                if (_y > _height - 120) StartPage(false);
                _pdf.Gray(0.1f);
                _pdf.Text(Margin, _y, 10, true, Clean(sectionHeading, 120));
                _y += 16;
            }
            if (count == 0)
            {
                _pdf.Gray(0.35f);
                _pdf.Text(Margin, _y, 8.5f, false, "No records matched the selected filters.");
                _y += 18;
                return;
            }

            float available = _width - Margin * 2;
            float[] widths = ComputeWidths(table, available, fontSize);
            float[] xs = new float[widths.Length];
            float acc = Margin;
            for (int i = 0; i < widths.Length; i++) { xs[i] = acc; acc += widths[i]; }

            DrawTableHeader(table, xs, widths, fontSize, lineHeight);

            for (int r = 0; r < table.Rows.Count; r++)
            {
                DataRow row = table.Rows[r];
                string[][] lines = new string[widths.Length][];
                int maxLines = 1;
                for (int c = 0; c < widths.Length; c++)
                {
                    lines[c] = Wrap(Cell(row[c]), widths[c] - 5, fontSize, false).ToArray();
                    if (lines[c].Length > maxLines) maxLines = lines[c].Length;
                }
                float rowHeight = maxLines * lineHeight + 5;

                if (_y + rowHeight > _height - 48)
                {
                    StartPage(false);
                    DrawTableHeader(table, xs, widths, fontSize, lineHeight);
                }
                if (r % 2 == 1) _pdf.Rect(Margin, _y - 2, available, rowHeight, true, 0.975f);
                _pdf.Gray(0.14f);
                for (int c = 0; c < widths.Length; c++)
                {
                    bool right = IsNumeric(table.Columns[c]);
                    for (int l = 0; l < lines[c].Length; l++)
                    {
                        float textX = xs[c] + 2;
                        if (right)
                        {
                            float w = Measure(lines[c][l], fontSize, false);
                            textX = Math.Max(xs[c] + 2, xs[c] + widths[c] - 3 - w);
                        }
                        _pdf.Text(textX, _y + 1 + l * lineHeight, fontSize, false, lines[c][l]);
                    }
                }
                _y += rowHeight;
                _pdf.Gray(0.88f);
                _pdf.LineWidth(0.35f);
                _pdf.Rule(Margin, _y - 1, _width - Margin, _y - 1);
                _pdf.Gray(0);
            }
            _y += 10;
        }

        private void DrawTableHeader(DataTable table, float[] xs, float[] widths, float fontSize, float lineHeight)
        {
            float available = _width - Margin * 2;
            var all = new string[widths.Length][];
            int maxLines = 1;
            for (int c = 0; c < widths.Length; c++)
            {
                string header = Clean(HeaderLabel(table.Columns[c].ColumnName), 60);
                all[c] = Wrap(header, widths[c] - 4, fontSize, true).ToArray();
                if (all[c].Length > maxLines) maxLines = all[c].Length;
            }
            float headerHeight = maxLines * lineHeight + 6;
            _pdf.Rect(Margin, _y - 2, available, headerHeight, true, 0.92f);
            _pdf.Gray(0.08f);
            for (int c = 0; c < widths.Length; c++)
            {
                for (int l = 0; l < all[c].Length; l++)
                    _pdf.Text(xs[c] + 2, _y + 1 + l * lineHeight, fontSize, true, all[c][l]);
            }
            _y += headerHeight;
            _pdf.Gray(0);
        }

        private static string HeaderLabel(string name)
        {
            if (string.IsNullOrEmpty(name)) return "";
            switch (name)
            {
                case "UserName": return "User";
                case "DetailJson": return "Details";
                case "CreatedAtUtc": return "Created";
                case "SubmittedAtUtc": return "Submitted";
                case "UpdatedAtUtc": return "Updated";
                case "StartedAtUtc": return "Started";
                case "ExpiresAtUtc": return "Expires";
                case "PaidAtUtc": return "Paid";
                case "AuditId": return "Entry";
                case "IpAddress": return "IP address";
                case "EntityTable": return "Area";
                case "EntityId": return "Record ID";
            }
            string text = name.Replace("_", " ");
            if (text.EndsWith("Utc", StringComparison.Ordinal)) text = text.Substring(0, text.Length - 3);
            text = System.Text.RegularExpressions.Regex.Replace(text, "([a-z0-9])([A-Z])", "$1 $2");
            return text;
        }

        private float[] ComputeWidths(DataTable table, float available, float fontSize)
        {
            int cols = table.Columns.Count;
            var weights = new double[cols];
            double total = 0;
            for (int c = 0; c < cols; c++)
            {
                double max = Math.Max(8, HeaderLabel(table.Columns[c].ColumnName).Length * 0.85);
                int sample = Math.Min(table.Rows.Count, 120);
                for (int r = 0; r < sample; r++)
                {
                    double len = Cell(table.Rows[r][c]).Length;
                    if (len > max) max = Math.Min(len, 42);
                }
                weights[c] = Math.Max(8.5, max);
                total += weights[c];
            }
            var widths = new float[cols];
            float used = 0;
            for (int c = 0; c < cols; c++) widths[c] = (float)(available * weights[c] / total);
            for (int c = 0; c < cols; c++) used += widths[c];
            widths[cols - 1] += available - used;
            return widths;
        }

        private static bool IsNumeric(DataColumn col)
        {
            Type t = col.DataType;
            if (t == typeof(int) || t == typeof(long) || t == typeof(decimal) || t == typeof(double) ||
                t == typeof(float) || t == typeof(short) || t == typeof(byte)) return true;
            string n = col.ColumnName.ToLowerInvariant();
            return n.Contains("amount") || n.Contains("total") || n.Contains("count") || n.Contains("percent") ||
                   n.Contains("marks") || n.Contains("rows") || n.Contains("fee") || n.Contains("balance");
        }

        private string Cell(object value)
        {
            if (value == null || value == DBNull.Value) return "";
            if (value is DateTime) { var d = (DateTime)value; return d.TimeOfDay == TimeSpan.Zero ? Fmt.Date(d, _zone) : Fmt.Stamp(d, _zone, "yyyy-MM-dd HH:mm"); }
            if (value is bool) return ((bool)value) ? "Yes" : "No";
            if (value is decimal) return ((decimal)value).ToString("N2", CultureInfo.InvariantCulture);
            if (value is double) return ((double)value).ToString("N2", CultureInfo.InvariantCulture);
            return Convert.ToString(value, CultureInfo.InvariantCulture);
        }

        private static string Clean(string text, int max)
        {
            if (string.IsNullOrEmpty(text)) return "";
            text = text.Replace("\r", " ").Replace("\n", " ").Replace("\t", " ");
            while (text.Contains("  ")) text = text.Replace("  ", " ");
            return text.Length > max ? text.Substring(0, max - 3) + "..." : text;
        }

        private static float Measure(string text, float size, bool bold)
        {
            if (string.IsNullOrEmpty(text)) return 0;
            float sum = 0;
            foreach (char c in text)
            {
                if (c == ' ') sum += 0.27f;
                else if ("il.,:;'!|".IndexOf(c) >= 0) sum += 0.25f;
                else if ("mwMW@%".IndexOf(c) >= 0) sum += 0.82f;
                else if (char.IsUpper(c)) sum += 0.65f;
                else sum += 0.52f;
            }
            return sum * size * (bold ? 1.04f : 1f);
        }

        private static int BreakIndex(string line, int limit)
        {
            int best = line.LastIndexOf(' ', limit);
            for (int i = limit; i > 1; i--)
            {
                char c = line[i - 1];
                if (c == '_' || c == '/' || c == '-' || c == ',' || c == ';' || c == ':')
                {
                    if (i > best) best = i;
                    break;
                }
            }
            for (int i = limit; i > 2; i--)
            {
                if (char.IsLower(line[i - 1]) && char.IsUpper(line[i]))
                {
                    if (i > best) best = i;
                    break;
                }
            }
            return best > 1 ? best : limit;
        }

        /// <summary>Word wrap with hard breaks for long tokens, so no cell overflows.</summary>
        private static List<string> Wrap(string text, float maxWidth, float size, bool bold)
        {
            var result = new List<string>();
            if (string.IsNullOrEmpty(text)) { result.Add(""); return result; }
            foreach (string rawLine in text.Replace("\r", "").Split('\n'))
            {
                string line = rawLine;
                while (line.Length > 0)
                {
                    if (Measure(line, size, bold) <= maxWidth) { result.Add(line); break; }
                    int cut = line.Length - 1;
                    while (cut > 1 && Measure(line.Substring(0, cut), size, bold) > maxWidth) cut--;
                    cut = BreakIndex(line, Math.Min(cut, line.Length - 1));
                    result.Add(line.Substring(0, cut).TrimEnd());
                    line = line.Substring(cut).TrimStart();
                }
            }
            if (result.Count == 0) result.Add("");
            return result;
        }

        private void Finish()
        {
            // If the document ended with a lot of empty space, leave it: the
            // footers are stamped on every page in Build().
        }
    }
}




